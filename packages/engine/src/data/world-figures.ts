/** 명부 한 줄 — 페르소나가 되기 전의 사실 */
export interface WorldFigureSeed {
  /** 전역 유일 — `characterId`이자 화면에 서는 이름 */
  name: string;
  /** ⚠️ `head_coach`는 우리 수석코치의 자리다. 타 팀 감독은 `manager`다 */
  role: PersonaRole;
  /**
   * 지금 이 사람이 앉아 있는 벤치 — **감독에게만 있고, 쓰이는 자리는 하나뿐이다**:
   * 세계가 생길 때 그 구단의 `GameTeam.managerName`을 심는다. 그 뒤 그가 어디에
   * 있는지는 명부가 아니라 `managerName`이 답한다 (경질·선임은 감독 시장의 일이다).
   */
  teamId?: string;
  archetype: string;
  traits: readonly string[];
  motivation: string;
  speech: { note: string; samples: readonly string[] };
  /**
   * 이 사람이 불렸다고 볼 말들 — **적으면 그것이 전부다**(기본값을 대체한다).
   *
   * 적지 않으면 전체 이름과 **성**으로 걸린다. 적어야 하는 경우는 둘이다:
   * 애칭·별명이 따로 있을 때, 그리고 **성이 흔한 말과 겹칠 때** — "치부"·"캐릭"은
   * 서사 문장에 그대로 들어 있을 수 있어서 성 호출을 꺼야 한다.
   */
  keywords?: readonly string[];
}

