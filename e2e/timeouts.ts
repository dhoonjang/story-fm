/**
 * 기다림은 **둘뿐이다** — 냉간과 왕복.
 *
 * 인라인 타임아웃이 40여 곳에서 10초·15초·20초·30초·40초로 갈려 있었다. 그 숫자
 * 하나하나에는 근거가 없었다: 같은 종류의 기다림이 파일마다 다른 값을 달고 있었고,
 * 어느 값이 무엇을 재는지 읽을 수 없으니 하나가 불안정해질 때마다 그 자리만 늘었다.
 *
 * 재는 것은 두 가지다.
 *
 * - **`COLD_MS`** — 아직 아무것도 데워지지 않은 자리. 라우트를 처음 두드리면 개발
 *   서버가 그 자리에서 컴파일하고(2.6초 관측), 새 게임의 첫 장면은 세계를 통째로
 *   짓는다. 둘 다 한 번씩만 치르고 그 뒤로는 빠르다.
 * - **`TURN_MS`** — 데워진 서버와의 왕복 한 번. 턴 하나, 자동 저장 하나(전술판은
 *   조작이 멎기를 3초 기다렸다가 보낸다), 화면 갱신 하나. **`playwright.config.ts`의
 *   `expect.timeout`이 이 값이므로**, 이 부류의 기다림은 스펙에서 아무것도 적지 않는
 *   것이 기본이다 — 적혀 있는 숫자는 곧 "여기는 기본과 다르다"는 뜻이 된다.
 *
 * 케이스 전체의 상한(`timeout: 90_000`)은 그대로다. 한 걸음이 여기서 늘어지면
 * 케이스가 그 상한에 걸려 죽고, 무엇이 멎었는지는 그때도 이 두 이름이 말한다.
 */

/** 냉간 — 라우트 첫 컴파일·첫 화면·새 게임의 첫 장면 */
export const COLD_MS = 40_000;

/** 왕복 한 번 — 턴·저장·화면 갱신 (`expect.timeout`의 기본값이다) */
export const TURN_MS = 20_000;
